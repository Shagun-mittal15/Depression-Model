def sleep_midpoint(sleep_str):
    try:
        sleep_str = str(sleep_str).strip()

        if '-' in sleep_str:       # normal range
            start, end = sleep_str.split('-')
            return (float(start) + float(end)) / 2
        elif '<' in sleep_str:     # like '<5'
            return float(sleep_str.replace('<','')) - 0.5  # estimate slightly below
        elif '>' in sleep_str:     # like '>8'
            return float(sleep_str.replace('>','')) + 0.5  # estimate slightly above
        else:                       # single number
            return float(sleep_str)
    except:
        return None  # missing or invalid

