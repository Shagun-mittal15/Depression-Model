from sklearn.preprocessing import FunctionTransformer

def preprocess_for_predict(df):
    df = df.copy()
    if "Age" in df:
        df['Age']=df['Age'].replace('25+','25-30')
        df["Age_mid"] = df["Age"].apply(age_midpoint)
        df = df.drop(columns=["Age"])
    if "Sleep Hours" in df:
        df["Sleep_mid"] = df["Sleep Hours"].apply(sleep_midpoint)
        df = df.drop(columns=["Sleep Hours"])
    return df

# Wrap in FunctionTransformer
